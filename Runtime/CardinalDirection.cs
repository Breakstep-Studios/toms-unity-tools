/// <summary>
/// Represents the four cardinal directions as well as the four intercardinal directions found on a compass
/// </summary>
public enum CardinalDirection
{
    /// <summary>
    /// Typically 315 to 45 degrees
    /// </summary>
    North,
    /// <summary>
    /// Typically 0 to 90 degrees
    /// </summary>
    NorthEast,
    /// <summary>
    /// Typically 45 to 135 degrees
    /// </summary>
    East,
    /// <summary>
    /// Typically 90 to 180 degrees
    /// </summary>
    SouthEast,
    /// <summary>
    /// Typically 135 to 225 degrees
    /// </summary>
    South,
    /// <summary>
    /// Typically 180 to 270 degrees
    /// </summary>
    SouthWest,
    /// <summary>
    /// Typically 225 to 315 degrees
    /// </summary>
    West,
    /// <summary>
    /// Typically 270 to 360 degrees
    /// </summary>
    NorthWest
}